package probe.b;

import com.tiffinbox.Database;
import com.tiffinbox.MealType;
import com.tiffinbox.TiffinBoxProperties;
import com.zaxxer.hikari.HikariDataSource;
import jakarta.persistence.EntityManagerFactory;
import org.hibernate.SessionFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.List;

/**
 * The shipped Database, built in code on this run's own database (H2 in this JVM's memory, or the run's fresh PostgreSQL database):
 * its createAndSeed creates the two tables and seeds Ravi, Meera, Sunil, Priya and two pauses. Boot's pool is wrapped in the counting
 * proxy (the third witness and the batching witnesses). The token is a placeholder, not a secret: nothing reads it. tables() makes the
 * harness's own tables by plain JDBC after the seed (ddl-auto none): x_ident (an identity column), x_seq and x_seq_seq (a sequence,
 * INCREMENT BY 50), w_customer / w_pause with their sequences and a version column on w_customer.
 */
@Configuration
public class Seed {
    @Bean
    Database database(@Value("${spring.datasource.url}") String jdbcUrl) {
        H.url = jdbcUrl;
        return new Database(new TiffinBoxProperties(jdbcUrl, 3, 30, 1, "127.0.0.1", List.of(MealType.VEG), "harness-only-placeholder"));
    }

    @Bean
    static BeanPostProcessor countingDataSource() {
        return new BeanPostProcessor() {
            @Override
            public Object postProcessAfterInitialization(Object bean, String name) {
                if (bean instanceof HikariDataSource h) return H.counting(h);
                if (bean instanceof EntityManagerFactory emf) H.sf = emf.unwrap(SessionFactory.class);
                return bean;
            }
        };
    }

    public static void tables() {
        for (String t : List.of("x_ident", "x_seq", "w_pause", "w_customer")) H.exec("DROP TABLE IF EXISTS " + t);
        for (String s : List.of("x_seq_seq", "w_customer_seq", "w_pause_seq")) H.exec("DROP SEQUENCE IF EXISTS " + s);
        H.exec("CREATE TABLE x_ident (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL, meals_per_day INT NOT NULL)");
        H.exec("CREATE TABLE x_seq (id BIGINT PRIMARY KEY, name VARCHAR(60) NOT NULL, meals_per_day INT NOT NULL)");
        H.exec("CREATE SEQUENCE x_seq_seq START WITH 1 INCREMENT BY 50");
        H.exec("CREATE TABLE w_customer (id BIGINT PRIMARY KEY, name VARCHAR(60) NOT NULL, meals_per_day INT NOT NULL, version BIGINT NOT NULL)");
        H.exec("CREATE TABLE w_pause (id BIGINT PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES w_customer(id), days INT NOT NULL)");
        H.exec("CREATE SEQUENCE w_customer_seq START WITH 1 INCREMENT BY 50");
        H.exec("CREATE SEQUENCE w_pause_seq START WITH 1 INCREMENT BY 50");
    }
}
