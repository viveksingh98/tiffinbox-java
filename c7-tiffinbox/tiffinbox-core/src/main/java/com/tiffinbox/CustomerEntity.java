package com.tiffinbox;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;

import java.util.ArrayList;
import java.util.List;

/**
 * Course 7, unit 03: a customer as an entity - a class Hibernate maps to a table and keeps track of. It maps the customer
 * table Database already creates and seeds; Hibernate writes no schema (application.yaml: ddl-auto none).
 *
 * <p>Beside the record {@link Customer}, not instead of it: a record's components are final, so a field could never be
 * changed on a loaded customer, and the record stays the web layer's validated value. CustomerRepository keeps two of its
 * five SQL strings since Course 7 unit 16 - findAll, add and findByName go through CustomerEntityRepository; both reach the same database.
 *
 * <p>The id is the table's own identity column (Database: GENERATED BY DEFAULT AS IDENTITY, since Course 7 unit 06): IDENTITY
 * asks the database for it, so the INSERT runs when persist is called. The fields map by Boot's naming - mealsPerDay to meals_per_day - with no column names written. The name's two
 * limits are one fact: {@code @Size(max = 60)} is what the validator checks before any SQL, {@code @Column(length = 60)} is
 * the column Database creates (VARCHAR(60)). Hibernate's generated DDL takes {@code @Size}'s limit over
 * {@code @Column(length)}, so the DDL alone cannot show the two agree: ../c7-unit03 reads both off this class.
 *
 * <p>The meal type is the anchor's own {@link MealType} since Course 7 unit 07, stored by its name: the column Database creates
 * is still VARCHAR(10), and its rows hold VEG, NON_VEG and VEGAN, which Hibernate reads back as those constants.
 *
 * <p>A customer's pauses since Course 7 unit 09: {@link PauseEntity} maps Database's pause table, whose customer_id column
 * holds the foreign key. That side owns the relationship; {@link #getPauses()} is the inverse side, read through it.
 */
@Entity
@Table(name = "customer")
public class CustomerEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @NotBlank
    @Size(max = 60)
    @Column(length = 60, nullable = false, unique = true)
    private String name;

    private int mealsPerDay;

    private int pricePerMeal;

    /**
     * Stored by the constant's name (STRING), never by its position (ORDINAL): a position changes when someone reorders the
     * enum, and the rows already written would then read back as another meal type, with no error anywhere (../c7-unit07).
     */
    @Enumerated(EnumType.STRING)
    @Column(length = 10, nullable = false)
    private MealType mealType;

    /**
     * The inverse side: mappedBy names the field that owns the foreign key, {@link PauseEntity}'s customer, so Hibernate
     * writes nothing for this list - it reads pause rows by their customer_id. A pause belongs to a customer when its
     * customer is set; one only added here is written with no customer (../c7-unit09).
     */
    @OneToMany(mappedBy = "customer")
    private List<PauseEntity> pauses = new ArrayList<>();

    /** For Hibernate, which builds an entity before it fills its fields. */
    protected CustomerEntity() {
    }

    public CustomerEntity(String name, int mealsPerDay, int pricePerMeal, MealType mealType) {
        this.name = name;
        this.mealsPerDay = mealsPerDay;
        this.pricePerMeal = pricePerMeal;
        this.mealType = mealType;
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public int getMealsPerDay() {
        return mealsPerDay;
    }

    /** The one change a customer takes here: the next lessons change it on a loaded entity and watch the SQL. */
    public void setMealsPerDay(int mealsPerDay) {
        this.mealsPerDay = mealsPerDay;
    }

    public int getPricePerMeal() {
        return pricePerMeal;
    }

    public MealType getMealType() {
        return mealType;
    }

    /** The customer's pauses, loaded from the pause table the first time the list is read. */
    public List<PauseEntity> getPauses() {
        return pauses;
    }
}
