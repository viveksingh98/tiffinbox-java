-- Course 8, unit 21: the dishes TiffinBox cooks - ten rows, English names, one meal type each, the menu's price for that meal type in
-- rupees (MenuDay's VEG_PRICE, NON_VEG_PRICE and VEGAN_PRICE). The rows are PostgreSQL's under the profile "dev" (and H2's on the default
-- run): the source. Elasticsearch's index dishes is a copy the "dev" start rebuilds from them (TiffinBoxServer). The ids are the
-- identity's, 1 to 10 in the order below, on a fresh database.
CREATE TABLE dish (
    id        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(80) NOT NULL UNIQUE,
    meal_type VARCHAR(10) NOT NULL,
    price     INT         NOT NULL
);
