package probe.w;

import com.tiffinbox.Database;
import com.tiffinbox.MealType;
import com.tiffinbox.TiffinBoxProperties;
import com.zaxxer.hikari.HikariDataSource;
import jakarta.persistence.EntityManagerFactory;
import org.hibernate.SessionFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.List;

/**
 * The shipped Database, built in code on this run's own database (H2 in this JVM's memory, or the run's fresh PostgreSQL database):
 * its createAndSeed creates the two tables and seeds Ravi, Meera, Sunil, Priya and two pauses (Sunil 3 days, Priya 2). Boot's pool
 * is wrapped in the counting proxy (the third witness). The harness's own table, meal_order (a second collection for the bags
 * step), is made by plain JDBC after the seed. The token is a placeholder, not a secret: nothing here reads it.
 */
@Configuration
public class Seed {
    @Bean
    Database database(@Value("${spring.datasource.url}") String jdbcUrl) {
        H.url = jdbcUrl;
        return new Database(new TiffinBoxProperties(jdbcUrl, 3, 30, 1, "127.0.0.1", List.of(MealType.VEG), "harness-only-placeholder"));
    }

    @Bean
    static BeanPostProcessor countingDataSource() {
        return new BeanPostProcessor() {
            @Override
            public Object postProcessAfterInitialization(Object bean, String name) {
                if (bean instanceof HikariDataSource h) return H.counting(h);
                if (bean instanceof EntityManagerFactory emf) H.sf = emf.unwrap(SessionFactory.class);
                return bean;
            }
        };
    }

    /** The harness's table meal_order, by plain JDBC: two orders for Ravi, three for Sunil, none for Meera and Priya. */
    public static void orders() {
        H.exec("DROP TABLE IF EXISTS meal_order");
        H.exec("CREATE TABLE meal_order (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES customer(id), meals INT NOT NULL)");
        for (int m : new int[]{2, 1}) H.exec("INSERT INTO meal_order (customer_id, meals) SELECT id, " + m + " FROM customer WHERE name = 'Ravi'");
        for (int m : new int[]{3, 2, 1}) H.exec("INSERT INTO meal_order (customer_id, meals) SELECT id, " + m + " FROM customer WHERE name = 'Sunil'");
    }
}
