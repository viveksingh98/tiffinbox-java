-- TiffinBox's schema, as the retired Database class created it (Course 7 units 06, 27 and 34): the two tables, the version column, the index.
CREATE TABLE customer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60) NOT NULL UNIQUE,
    meals_per_day INT         NOT NULL,
    price_per_meal INT        NOT NULL,
    meal_type     VARCHAR(10) NOT NULL,
    version       BIGINT      NOT NULL DEFAULT 0
);
CREATE TABLE pause (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    days        INT    NOT NULL
);
CREATE INDEX pause_customer_id_idx ON pause (customer_id);
