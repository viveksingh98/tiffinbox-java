package probe.d.ex;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import org.springframework.boot.SpringApplication;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.boot.persistence.autoconfigure.EntityScan;

import java.sql.DriverManager;

/**
 * Unit 35's exercise, ONE JVM on an H2 database in its own memory (no port, no container, never TiffinBox's tables): a diner table
 * of its own is created and seeded by plain JDBC with an integer meals_per_day column, then Spring starts with the arguments given
 * (the ddl-auto value among them) over an entity, Diner, whose mealsPerDay is a String. It prints the column's type before and after
 * the start, read over a plain JDBC connection of its own, and whether the start went on.
 */
@SpringBootApplication
@EntityScan("probe.d.ex")
public class Ex {
    static final String URL = "jdbc:h2:mem:diner;DB_CLOSE_DELAY=-1";

    @Entity(name = "Diner")
    public static class Diner {
        @Id @GeneratedValue(strategy = GenerationType.IDENTITY) Long id;
        String name;
        String mealsPerDay;
    }

    static String type() throws Exception {
        try (var c = DriverManager.getConnection(URL, "sa", ""); var st = c.createStatement();
             var rs = st.executeQuery("select lower(data_type) || coalesce('(' || character_maximum_length || ')', '') from information_schema.columns where table_name = 'DINER' and column_name = 'MEALS_PER_DAY'")) {
            return rs.next() ? rs.getString(1) : "(no column)";
        }
    }

    public static void main(String[] args) throws Exception {
        System.out.println("PROBE version: Hibernate " + org.hibernate.Version.getVersionString());
        try (var c = DriverManager.getConnection(URL, "sa", ""); var st = c.createStatement()) {
            st.execute("CREATE TABLE diner (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255), meals_per_day INT NOT NULL)");
            st.execute("INSERT INTO diner (name, meals_per_day) VALUES ('Ravi', 2), ('Meera', 1), ('Sunil', 3)");
        }
        System.out.println("PROBE before the start: diner.meals_per_day " + type());
        var app = new SpringApplication(Ex.class);
        app.setWebApplicationType(WebApplicationType.NONE);
        app.setDefaultProperties(java.util.Map.of("spring.datasource.url", URL));
        int code = 0;
        try (var ctx = app.run(args)) {
            System.out.println("PROBE ready: yes");
        } catch (Throwable t) {
            code = 1;
            System.out.println("PROBE ready: no");
            Throwable c = t;
            while (c.getCause() != null && c.getCause() != c) c = c.getCause();
            System.out.println("PROBE refused: " + c.getClass().getSimpleName() + ": " + String.valueOf(c.getMessage()).lines().findFirst().orElse(""));
        }
        System.out.println("PROBE after the start: diner.meals_per_day " + type());
        System.exit(code);
    }
}
