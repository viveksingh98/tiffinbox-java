package probe.q.casc;

import com.tiffinbox.Database;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.sql.DriverManager;
import java.sql.SQLException;

/**
 * The cascade pair's two tables, created on this run's own database by plain JDBC once the shipped Database has seeded its own
 * (Hibernate writes no schema: ddl-auto none). c_pause.customer_id references c_customer(id): the same foreign key the anchor's
 * pause table holds, so a bulk delete meets the same refusal.
 */
@Configuration
public class Tables {
    public static final String CUSTOMER = "CREATE TABLE c_customer (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60))";
    public static final String PAUSE = "CREATE TABLE c_pause (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES c_customer(id), days INT NOT NULL)";

    @Bean
    String cascadeTables(Database database, @Value("${spring.datasource.url}") String url) throws SQLException {
        try (var c = DriverManager.getConnection(url, "sa", ""); var st = c.createStatement()) {
            st.execute(CUSTOMER);
            st.execute(PAUSE);
        }
        return "c_customer, c_pause";
    }
}
